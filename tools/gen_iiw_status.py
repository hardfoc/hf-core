#!/usr/bin/env python3
"""Write handlers/common/IiwStatus.h: ``hf::ToStatus()`` for every ``hf_*_err_t`` in interface-wrap.

The error codes come from the ``HF_<X>_ERR_LIST(X)`` X-macro tables in
``hf-core-drivers/internal/hf-internal-interface-wrap/inc/base/Base*.h``, so the header always covers
the interface-wrap revision the submodule pins. The mapping onto ``hf::Status`` is the name rules in
``tools/status_rules.py``. Every code becomes its own ``case`` with no ``default``: a code added upstream
without regenerating this header is a ``-Wswitch`` error in the host build, and the ``iiw_status_fresh``
test fails until the header is regenerated.

Usage:
  python3 tools/gen_iiw_status.py           rewrite the header
  python3 tools/gen_iiw_status.py --check   exit 1 when the header is stale
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import status_rules  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT / "hf-core-drivers/internal/hf-internal-interface-wrap/inc/base"
OUT = ROOT / "handlers/common/IiwStatus.h"

LIST_RE = re.compile(r"^#define (HF_(\w+)_ERR_LIST)\(X\)[ \t]*\\\n(.*?)(?<!\\)\n(?=\S|\n)", re.M | re.S)
ENTRY_RE = re.compile(r"X\((\w+),\s*(-?\d+)\s*,")


def tables() -> list[dict]:
    out = []
    for header in sorted(BASE.glob("Base*.h")):
        text = header.read_text(encoding="utf-8")
        for m in LIST_RE.finditer(text):
            macro, short, body = m.group(1), m.group(2), m.group(3)
            enum = re.search(rf"enum class (hf_\w+_err_t)\b[^{{;]*\{{([^}}]*{macro}[^}}]*)\}}", text, re.S)
            if enum:
                name, enum_body = enum.group(1), enum.group(2)
            else:
                enum = re.search(rf"typedef enum\s*\{{([^}}]*{macro}[^}}]*)\}}\s*(hf_\w+_err_t)\s*;", text, re.S)
                if not enum:
                    raise SystemExit(f"[gen_iiw_status] no enum built from {macro} in {header.name}")
                name, enum_body = enum.group(2), enum.group(1)
            entries = ENTRY_RE.findall(body)
            # Enumerators written after the table (a GPIO_ERR_COUNT sentinel) take the next values.
            rest = re.sub(r"/\*.*?\*/", "", enum_body, flags=re.S)
            rest = re.sub(r"//[^\n]*|^[ \t]*#[^\n]*", "", rest, flags=re.M).replace(macro, "")
            rest = re.sub(r"\(\s*\w+\s*\)", "", rest)
            nxt = max(int(v) for _n, v in entries) + 1
            for extra in re.findall(r"\b([A-Z][A-Z0-9_]+)\b", rest):
                entries.append((extra, str(nxt)))
                nxt += 1
            values = [v for _n, v in entries]
            dupes = sorted({v for v in values if values.count(v) > 1})
            if dupes:
                raise SystemExit(f"[gen_iiw_status] {name} repeats values {dupes}; a switch cannot list both")
            out.append({"header": header.name, "enum": name, "prefix": short,
                        "codes": [(n, int(v), status_rules.classify(n, short)) for n, v in entries]})
    if not out:
        raise SystemExit(f"[gen_iiw_status] no HF_*_ERR_LIST tables under {BASE}")
    return out


def render(ts: list[dict]) -> str:
    lines = [
        "/**",
        " * @file IiwStatus.h",
        " * @brief `hf::ToStatus()` and `hf::ToResult()` for every interface-wrap `hf_*_err_t`.",
        " *",
        " * GENERATED by tools/gen_iiw_status.py from the HF_*_ERR_LIST tables of the interface-wrap revision",
        " * hf-core pins; the mapping rules are in tools/status_rules.py. Do not edit by hand: change the rules",
        " * and run `python3 tools/gen_iiw_status.py`. The `iiw_status_fresh` host test fails when this file",
        " * is stale, and every switch lists every code without a `default`, so a code added upstream is a",
        " * -Wswitch error until the header is regenerated.",
        " *",
        " * `ToResult(e)` keeps the native code as `detail()`, so a log still shows, say, I2C_ERR_DEVICE_NACK",
        " * behind `Status::Bus`.",
        " *",
        " * @copyright Copyright (c) 2026 HardFOC. All rights reserved.",
        " */",
        "#pragma once",
        "",
        "#include <cstdint>",
        "#include <type_traits>",
        "",
        '#include "HfResult.h"',
        "",
    ]
    lines += [f'#include "base/{h}"' for h in sorted({t["header"] for t in ts})]
    lines += ["", "namespace hf {", ""]
    for t in ts:
        e = t["enum"]
        lines += [
            f"/// `hf::Status` for a `{e}` ({t['header']}).",
            f"[[nodiscard]] constexpr Status ToStatus({e} error) noexcept {{",
            "    switch (error) {",
        ]
        for name, value, status in t["codes"]:
            lines.append(f"    case {e}::{name}:  // {value}")
            lines.append(f"        return Status::{status};")
        lines += ["    }", "    return Status::Unknown;", "}", ""]
    enums = " ||\n    ".join(f"std::is_same_v<E, {t['enum']}>" for t in ts)
    lines += [
        "/// True for the interface-wrap error enums `ToStatus()` covers.",
        "template <typename E>",
        "inline constexpr bool kIsIiwError =",
        f"    {enums};",
        "",
        "/// `Ok()` for a success code, otherwise a failure with `ToStatus(error)` and the native code as detail.",
        "template <typename E>",
        "    requires kIsIiwError<E>",
        "[[nodiscard]] constexpr Result<void> ToResult(E error) noexcept {",
        "    const Status status = ToStatus(error);",
        "    if (status == Status::Ok) {",
        "        return {};",
        "    }",
        "    return Fail(status, static_cast<std::uint32_t>(error));",
        "}",
        "",
        "}  // namespace hf",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="exit 1 when the header is stale")
    args = parser.parse_args()
    text = render(tables())
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"[gen_iiw_status] {OUT.relative_to(ROOT)} is stale: run python3 tools/gen_iiw_status.py",
                  file=sys.stderr)
            return 1
        print(f"[gen_iiw_status] {OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"[gen_iiw_status] wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
